"""Generate Codex agent files from the Claude Code agents.

`agents/*.md` is the single source. Codex reads custom agents as TOML (`name`, `description`,
`developer_instructions`), so this script writes `codex/agents/<name>.toml` from each Markdown file.
Model and tool lines are Claude Code specific and are not copied.

    python scripts/sync_codex_agents.py           # write codex/agents/*.toml
    python scripts/sync_codex_agents.py --check   # exit 1 if any file is missing or stale (used by tests)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "agents"
TARGET = ROOT / "codex" / "agents"
HEADER = "# Generated by scripts/sync_codex_agents.py from agents/{name}.md - edit the source, then re-run.\n"


def parse(text: str, name: str) -> tuple[dict[str, str], str]:
    """Split single-line `key: value` front matter from the body."""
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{name}: front matter must start with ---")
    end = lines.index("---", 1)
    fields = {}
    for line in lines[1:end]:
        if line.strip():
            key, _, value = line.partition(":")
            fields[key.strip()] = value.strip()
    return fields, "\n".join(lines[end + 1:]).strip()


def render(path: Path) -> str:
    fields, body = parse(path.read_text(encoding="utf-8"), path.stem)
    if fields.get("name") != path.stem:
        raise ValueError(f"{path.name}: name must match the file name")
    if "'''" in body:
        raise ValueError(f"{path.name}: body may not contain ''' (TOML literal string delimiter)")
    return (HEADER.format(name=path.stem)
            + f"name = {json.dumps(fields['name'])}\n"
            + f"description = {json.dumps(fields['description'], ensure_ascii=False)}\n"
            + f"developer_instructions = '''\n{body}\n'''\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report missing or stale files")
    args = ap.parse_args(argv)
    expected = {TARGET / f"{p.stem}.toml": render(p) for p in sorted(SOURCE.glob("*.md"))}
    stale = [p for p, text in expected.items()
             if not p.exists() or p.read_text(encoding="utf-8") != text]
    extra = [p for p in TARGET.glob("*.toml") if p not in expected] if TARGET.exists() else []
    if args.check:
        for p in stale + extra:
            print(f"out of sync: {p.relative_to(ROOT).as_posix()}")
        return 1 if stale or extra else 0
    TARGET.mkdir(parents=True, exist_ok=True)
    for p in stale:
        p.write_text(expected[p], encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT).as_posix()}")
    for p in extra:
        p.unlink()
        print(f"removed {p.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
